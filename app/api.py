"""REST API serving the churn model.

Run:  uvicorn app.api:app --reload
Docs: http://127.0.0.1:8000/docs  (interactive Swagger UI, generated by FastAPI)
"""
import json
import time
from contextlib import asynccontextmanager
from typing import Literal

import joblib
import pandas as pd
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

from app import db
from app.drift import drift_report
from app.features import ALL_FEATURES, MODEL_DIR

YesNo = Literal["Yes", "No"]
MIN_SAMPLES_FOR_DRIFT = 50

state: dict = {}


@asynccontextmanager
async def lifespan(app: FastAPI):
    # Load the model once at startup, not on every request.
    model_path = MODEL_DIR / "model.joblib"
    if not model_path.exists():
        raise RuntimeError("No trained model found. Run `python -m app.train` first.")
    state["model"] = joblib.load(model_path)
    state["metrics"] = json.loads((MODEL_DIR / "metrics.json").read_text())
    state["drift_ref"] = json.loads((MODEL_DIR / "drift_reference.json").read_text())
    db.init_db()
    yield
    state.clear()


app = FastAPI(title="Telecom Churn Prediction API", version="1.0.0", lifespan=lifespan)


class Customer(BaseModel):
    """Input schema. Pydantic rejects bad input with a clear 422 error
    before it ever reaches the model."""
    tenure: int = Field(ge=0, le=100, description="Months with the company")
    MonthlyCharges: float = Field(gt=0)
    TotalCharges: float | None = Field(default=None, ge=0)
    SeniorCitizen: Literal[0, 1] = 0
    gender: Literal["Male", "Female"]
    Partner: YesNo
    Dependents: YesNo
    PhoneService: YesNo
    MultipleLines: Literal["Yes", "No", "No phone service"]
    InternetService: Literal["DSL", "Fiber optic", "No"]
    OnlineSecurity: Literal["Yes", "No", "No internet service"]
    OnlineBackup: Literal["Yes", "No", "No internet service"]
    DeviceProtection: Literal["Yes", "No", "No internet service"]
    TechSupport: Literal["Yes", "No", "No internet service"]
    StreamingTV: Literal["Yes", "No", "No internet service"]
    StreamingMovies: Literal["Yes", "No", "No internet service"]
    Contract: Literal["Month-to-month", "One year", "Two year"]
    PaperlessBilling: YesNo
    PaymentMethod: Literal["Electronic check", "Mailed check",
                           "Bank transfer (automatic)", "Credit card (automatic)"]


class Prediction(BaseModel):
    churn_probability: float
    will_churn: bool
    risk_level: Literal["low", "medium", "high"]


class BatchRequest(BaseModel):
    customers: list[Customer] = Field(min_length=1, max_length=1000)


def risk_level(p: float) -> str:
    if p >= 0.6:
        return "high"
    if p >= 0.3:
        return "medium"
    return "low"


def predict_many(customers: list[Customer]) -> list[Prediction]:
    records = [c.model_dump() for c in customers]
    df = pd.DataFrame(records)[ALL_FEATURES]
    probas = state["model"].predict_proba(df)[:, 1]
    results = [Prediction(churn_probability=round(float(p), 4),
                          will_churn=bool(p >= state["metrics"]["threshold"]),
                          risk_level=risk_level(p)) for p in probas]
    db.log_predictions(
        [(r, res.churn_probability, res.risk_level) for r, res in zip(records, results)],
        state["metrics"]["model"],
    )
    return results


@app.get("/health")
def health():
    return {"status": "ok", "model_loaded": "model" in state}


@app.get("/model/info")
def model_info():
    m = state["metrics"]
    return {k: m[k] for k in ("model", "threshold", "test_roc_auc", "test_precision",
                              "test_recall", "test_f1", "n_train")}


@app.post("/predict", response_model=Prediction)
def predict(customer: Customer):
    return predict_many([customer])[0]


@app.post("/predict/batch")
def predict_batch(req: BatchRequest):
    start = time.perf_counter()
    results = predict_many(req.customers)
    return {"predictions": results,
            "count": len(results),
            "latency_ms": round((time.perf_counter() - start) * 1000, 2)}


@app.get("/monitoring/stats")
def monitoring_stats():
    return db.summary_stats()


@app.get("/monitoring/drift")
def monitoring_drift(window: int = 1000):
    rows = db.recent_features(limit=window)
    if len(rows) < MIN_SAMPLES_FOR_DRIFT:
        raise HTTPException(
            status_code=400,
            detail=f"Need at least {MIN_SAMPLES_FOR_DRIFT} logged predictions, "
                   f"have {len(rows)}.")
    report = drift_report(state["drift_ref"], pd.DataFrame(rows))
    worst = max(report.values(), key=lambda r: r["psi"])["status"]
    return {"samples": len(rows), "overall_status": worst, "features": report}
